import React, { useState } from 'react';
import { 
  Copy, 
  Check, 
  Download, 
  GitCommit, 
  FileDiff, 
  Sparkles,
  Terminal
} from 'lucide-react';

export default function DiffViewer({ diff, isStreaming }) {
  const [copied, setCopied] = useState(false);

  const handleCopy = () => {
    if (!diff) return;
    navigator.clipboard.writeText(diff);
    setCopied(true);
    setTimeout(() => setCopied(false), 2200);
  };

  const handleDownload = () => {
    if (!diff) return;
    const blob = new Blob([diff], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `project_x_fix_${Date.now()}.patch`;
    a.click();
    URL.revokeObjectURL(url);
  };

  // Compute addition and deletion counts
  const lines = diff ? diff.split('\n') : [];
  const additions = lines.filter(l => l.startsWith('+') && !l.startsWith('+++')).length;
  const deletions = lines.filter(l => l.startsWith('-') && !l.startsWith('---')).length;

  return (
    <div className="rounded-xl border border-border bg-card/80 overflow-hidden shadow-xl flex flex-col">
      {/* Diff Toolbar */}
      <div className="px-4 py-2.5 bg-surface border-b border-border flex items-center justify-between">
        <div className="flex items-center space-x-2">
          <FileDiff className="w-4 h-4 text-nebius" />
          <span className="text-xs font-semibold uppercase tracking-wider text-slate-300">
            Unified Git Diff Patch
          </span>
          {diff && (
            <div className="flex items-center space-x-1.5 ml-2 font-mono text-[11px]">
              <span className="px-1.5 py-0.5 rounded bg-emerald-500/15 text-emerald-400 border border-emerald-500/30">
                +{additions}
              </span>
              <span className="px-1.5 py-0.5 rounded bg-rose-500/15 text-rose-400 border border-rose-500/30">
                -{deletions}
              </span>
            </div>
          )}
        </div>

        {/* Action Buttons */}
        <div className="flex items-center space-x-2">
          {diff && (
            <>
              <button
                onClick={handleDownload}
                className="flex items-center space-x-1 px-2.5 py-1 rounded-md bg-slate-800 hover:bg-slate-700 text-slate-300 text-xs font-medium border border-border transition-colors"
                title="Download .patch file"
              >
                <Download className="w-3.5 h-3.5 text-slate-400" />
                <span className="hidden sm:inline">Export</span>
              </button>

              <button
                onClick={handleCopy}
                className={`flex items-center space-x-1.5 px-3 py-1 rounded-md text-xs font-medium transition-all ${
                  copied
                    ? 'bg-emerald-500/20 text-emerald-300 border border-emerald-500/40'
                    : 'bg-nebius/10 hover:bg-nebius/20 text-nebius border border-nebius/30'
                }`}
                title="Copy unified diff to clipboard"
              >
                {copied ? (
                  <>
                    <Check className="w-3.5 h-3.5 text-emerald-400" />
                    <span>Copied!</span>
                  </>
                ) : (
                  <>
                    <Copy className="w-3.5 h-3.5" />
                    <span>Copy Patch</span>
                  </>
                )}
              </button>
            </>
          )}
        </div>
      </div>

      {/* Code Display Area */}
      <div className="p-4 bg-background/95 overflow-x-auto min-h-[260px] max-h-[380px] font-mono text-xs leading-relaxed">
        {!diff ? (
          <div className="h-full min-h-[220px] flex flex-col items-center justify-center text-slate-500 space-y-3">
            <Terminal className="w-8 h-8 opacity-40 text-slate-400" />
            <div className="text-center">
              <p className="font-sans text-sm font-medium text-slate-400">
                Unified Diff Viewer Ready
              </p>
              <p className="text-xs text-slate-600 mt-0.5 max-w-sm">
                Run triage to synthesize an automated unified patch generated by NVIDIA Nemotron 70B.
              </p>
            </div>
          </div>
        ) : (
          <div className="space-y-0.5 select-text">
            {lines.map((line, idx) => {
              let lineStyle = "text-slate-300 py-0.5 px-2 rounded";
              let prefixIcon = null;

              if (line.startsWith('+++') || line.startsWith('---')) {
                lineStyle = "diff-line-header px-2 py-0.5 rounded font-bold";
              } else if (line.startsWith('@@')) {
                lineStyle = "diff-line-meta px-2 py-0.5 rounded font-semibold";
              } else if (line.startsWith('+')) {
                lineStyle = "diff-line-add px-2 py-0.5 rounded";
              } else if (line.startsWith('-')) {
                lineStyle = "diff-line-del px-2 py-0.5 rounded";
              }

              return (
                <div key={idx} className={`flex items-start ${lineStyle}`}>
                  <span className="w-8 select-none text-slate-600 text-right pr-3 font-mono text-[10px]">
                    {idx + 1}
                  </span>
                  <pre className="flex-1 whitespace-pre-wrap break-all font-mono">
                    {line || ' '}
                  </pre>
                </div>
              );
            })}
            {isStreaming && (
              <div className="flex items-center space-x-1 py-1 px-2 text-nebius animate-pulse">
                <span className="w-2 h-4 bg-nebius inline-block"></span>
                <span className="text-[11px] font-sans italic text-slate-400">
                  Nemotron-70B generating diff stream...
                </span>
              </div>
            )}
          </div>
        )}
      </div>
    </div>
  );
}
