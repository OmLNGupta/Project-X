import React, { useState } from 'react';
import { 
  Copy, 
  Check, 
  Download, 
  GitCommit, 
  FileDiff, 
  Sparkles,
  Terminal
} from 'lucide-react';

export default function DiffViewer({ diff, isStreaming }) {
  const [copied, setCopied] = useState(false);

  const handleCopy = () => {
    if (!diff) return;
    navigator.clipboard.writeText(diff);
    setCopied(true);
    setTimeout(() => setCopied(false), 2200);
  };

  const handleDownload = () => {
    if (!diff) return;
    const blob = new Blob([diff], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `project_x_fix_${Date.now()}.patch`;
    a.click();
    URL.revokeObjectURL(url);
  };

  // Compute addition and deletion counts
  const lines = diff ? diff.split('\n') : [];
  const additions = lines.filter(l => l.startsWith('+') && !l.startsWith('+++')).length;
  const deletions = lines.filter(l => l.startsWith('-') && !l.startsWith('---')).length;

  return (
    <div className="rounded-2xl bg-white/45 backdrop-blur-2xl border border-white/70 shadow-[0_8px_32px_0_rgba(31,38,135,0.08)] shadow-[inset_0_1px_1px_0_rgba(255,255,255,0.9)] overflow-hidden flex flex-col">
      {/* Diff Toolbar */}
      <div className="px-5 py-3.5 bg-white/30 border-b border-white/50 flex items-center justify-between">
        <div className="flex items-center space-x-2.5">
          <FileDiff className="w-4 h-4 text-teal-600" />
          <span className="text-xs font-bold uppercase tracking-wider text-slate-800">
            Unified Git Diff Patch
          </span>
          {diff && (
            <div className="flex items-center space-x-1.5 ml-2 font-mono text-[11px]">
              <span className="px-2 py-0.5 rounded-full bg-emerald-500/20 text-emerald-800 border border-emerald-300 font-semibold shadow-sm">
                +{additions}
              </span>
              <span className="px-2 py-0.5 rounded-full bg-rose-500/20 text-rose-800 border border-rose-300 font-semibold shadow-sm">
                -{deletions}
              </span>
            </div>
          )}
        </div>

        {/* Action Buttons */}
        <div className="flex items-center space-x-2">
          {diff && (
            <>
              <button
                onClick={handleDownload}
                className="flex items-center space-x-1.5 px-3 py-1.5 rounded-full bg-white/60 hover:bg-white/80 text-slate-700 text-xs font-semibold border border-white/80 shadow-sm transition-all"
                title="Download .patch file"
              >
                <Download className="w-3.5 h-3.5 text-slate-500" />
                <span className="hidden sm:inline">Export</span>
              </button>

              <button
                onClick={handleCopy}
                className={`flex items-center space-x-1.5 px-3.5 py-1.5 rounded-full text-xs font-semibold transition-all shadow-sm ${
                  copied
                    ? 'bg-emerald-100 text-emerald-800 border border-emerald-300'
                    : 'bg-white/70 hover:bg-white text-teal-800 border border-teal-200'
                }`}
                title="Copy unified diff to clipboard"
              >
                {copied ? (
                  <>
                    <Check className="w-3.5 h-3.5 text-emerald-600" />
                    <span>Copied!</span>
                  </>
                ) : (
                  <>
                    <Copy className="w-3.5 h-3.5 text-teal-600" />
                    <span>Copy Patch</span>
                  </>
                )}
              </button>
            </>
          )}
        </div>
      </div>

      {/* Code Display Area: Dark Glass Terminal Style */}
      <div className="p-3 sm:p-4">
        <div className="bg-slate-950/85 backdrop-blur-xl border border-white/20 rounded-xl p-4 text-xs font-mono shadow-xl overflow-x-auto min-h-[240px] max-h-[420px] select-text leading-relaxed">
          {!diff ? (
            <div className="h-full min-h-[200px] flex flex-col items-center justify-center text-slate-400 space-y-3">
              <div className="w-10 h-10 rounded-xl bg-white/5 border border-white/10 flex items-center justify-center">
                <Terminal className="w-5 h-5 text-slate-400 opacity-60" />
              </div>
              <div className="text-center">
                <p className="font-sans text-sm font-semibold text-slate-200">
                  Unified Diff Viewer Ready
                </p>
                <p className="text-xs text-slate-400 mt-1 max-w-sm">
                  Run autonomous triage to synthesize an automated unified patch generated by NVIDIA Nemotron 70B.
                </p>
              </div>
            </div>
          ) : (
            <div className="space-y-0.5">
              {lines.map((line, idx) => {
                let lineStyle = "text-slate-300 py-0.5 px-2 rounded-sm";

                if (line.startsWith('+++') || line.startsWith('---')) {
                  lineStyle = "diff-line-header px-2 py-0.5 rounded-sm font-bold text-xs";
                } else if (line.startsWith('@@')) {
                  lineStyle = "diff-line-meta px-2 py-0.5 rounded-sm font-semibold text-xs";
                } else if (line.startsWith('+')) {
                  lineStyle = "bg-emerald-500/15 text-emerald-300 border-l-2 border-emerald-500 px-2 py-0.5 rounded-sm";
                } else if (line.startsWith('-')) {
                  lineStyle = "bg-rose-500/15 text-rose-300 border-l-2 border-rose-500 px-2 py-0.5 rounded-sm";
                }

                return (
                  <div key={idx} className={`flex items-start ${lineStyle}`}>
                    <span className="w-8 select-none text-slate-500 text-right pr-3 font-mono text-[10px] shrink-0">
                      {idx + 1}
                    </span>
                    <pre className="flex-1 whitespace-pre-wrap break-all font-mono">
                      {line || ' '}
                    </pre>
                  </div>
                );
              })}
              {isStreaming && (
                <div className="flex items-center space-x-2 py-2 px-2 text-cyan-400 animate-pulse font-sans">
                  <span className="w-2 h-4 bg-cyan-400 inline-block rounded-sm shadow-[0_0_8px_#22d3ee]"></span>
                  <span className="text-xs italic text-slate-400">
                    Nemotron-70B generating diff stream...
                  </span>
                </div>
              )}
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
